#!/usr/bin/env node
/**
 * Build summarized GitHub Release notes from a detailed series section.
 *
 * Reads changelog/series/X.Y.x.md → writes changelog/releases/<version>.md
 *
 * Usage:
 *   node scripts/release/summarize-changelog-release.mjs <version> [--write] [changelogDir]
 *
 * Without --write, prints the release draft to stdout.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  extractVersionSection,
  normalizeVersion,
  seriesFileNameForVersion,
} from "./extract-changelog-section.mjs";

const SKIP_THEMES = new Set(["Developer", "Architecture"]);
const INTERNAL_BULLET =
  /\b(src\/|stores\/|lib\/desktop-api|pnpm typecheck|Phase \d+|IPC handler|preload\/|facade\.|domain folders|monolith is gone|re-export|imports Electron)\b/i;

/** User-facing themes first; anything else follows alphabetically. */
const THEME_PRIORITY = [
  "Workbench",
  "Chat",
  "Agent",
  "Runtime",
  "Shell",
  "Settings",
  "Literature",
  "Website",
  "Under the hood",
];

/**
 * @param {string} body detailed section body
 * @returns {Map<string, string[]>}
 */
export function parseThemeSections(body) {
  /** @type {Map<string, string[]>} */
  const sections = new Map();
  let currentTheme = null;

  for (const line of body.split("\n")) {
    if (line.startsWith("### ")) {
      currentTheme = line.slice(4).trim();
      if (!sections.has(currentTheme)) {
        sections.set(currentTheme, []);
      }
      continue;
    }
    if (line.startsWith("- ") && currentTheme) {
      sections.get(currentTheme).push(line.slice(2).trim());
    }
  }

  return sections;
}

/**
 * @param {string} text
 * @returns {boolean}
 */
export function isInternalBullet(text) {
  return INTERNAL_BULLET.test(text);
}

/**
 * @param {string} theme
 * @param {string[]} bullets
 * @param {number} maxBullets
 * @returns {string[]}
 */
export function summarizeThemeBullets(theme, bullets, maxBullets = 8) {
  const userFacing = bullets.filter((bullet) => !isInternalBullet(bullet));
  const pool = userFacing.length > 0 ? userFacing : bullets;

  if (pool.length <= maxBullets) {
    return pool.map((bullet) => `- ${bullet}`);
  }

  const kept = pool.slice(0, maxBullets - 1);
  kept.push(
    `Plus ${pool.length - (maxBullets - 1)} more ${theme.toLowerCase()} improvements in this release.`,
  );
  return kept.map((bullet) => `- ${bullet}`);
}

/**
 * @param {Map<string, string[]>} sections
 * @returns {Map<string, string[]>}
 */
export function mergeForRelease(sections) {
  /** @type {Map<string, string[]>} */
  const merged = new Map();

  for (const [theme, bullets] of sections) {
    if (SKIP_THEMES.has(theme)) continue;
    if (!merged.has(theme)) merged.set(theme, []);
    merged.get(theme).push(...bullets);
  }

  if (sections.has("Architecture") || sections.has("Developer")) {
    merged.set("Under the hood", [
      "Embedded Pi agent host replaces OpenCode — chat, providers, skills, MCP, Plan mode, and Task delegation run through the product agent API.",
      "Workbench storage moves to ~/.prismnext/ and <project>/.workbench/; sessions, libraries, worktrees, and skills use the new layout.",
      "Main and renderer reorganized into domain modules; the renderer talks to Electron only through lib/desktop-api/ ports.",
      "TypeScript 7 type-checking, Vite 7 / electron-vite 5 toolchain, and Electron 43 runtime upgrade.",
    ]);
  }

  return merged;
}

/**
 * @param {Map<string, string[]>} merged
 * @returns {string[]}
 */
export function orderThemes(merged) {
  const themes = [...merged.keys()];
  const rank = (theme) => {
    const index = THEME_PRIORITY.indexOf(theme);
    return index === -1 ? THEME_PRIORITY.length + themes.indexOf(theme) : index;
  };
  return themes.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
}

/**
 * @param {string} version
 * @param {string} detailedBody
 * @returns {string}
 */
export function buildReleaseNotes(version, detailedBody) {
  const v = normalizeVersion(version);
  const sections = parseThemeSections(detailedBody);
  const merged = mergeForRelease(sections);
  const lines = [
    `<!-- Generated by summarize-changelog-release.mjs for ${v}. Edit before shipping if needed. -->`,
    "",
  ];

  const intro = extractIntro(detailedBody);
  if (intro) {
    lines.push(intro, "");
  }

  for (const theme of orderThemes(merged)) {
    const bullets = merged.get(theme);
    if (!bullets || bullets.length === 0) continue;
    lines.push(`### ${theme}`, ...summarizeThemeBullets(theme, bullets), "");
  }

  return lines.join("\n").trim() + "\n";
}

/**
 * @param {string} body
 * @returns {string | null}
 */
function extractIntro(body) {
  const lines = [];
  for (const line of body.split("\n")) {
    if (line.startsWith("### ") || line.startsWith("- ")) break;
    const trimmed = line.trim();
    if (trimmed) lines.push(trimmed);
  }
  return lines.length > 0 ? lines.join(" ") : null;
}

/**
 * @param {string} version
 * @param {string} changelogRoot
 * @returns {{ seriesFile: string, detailedBody: string, releaseFile: string, releaseNotes: string }}
 */
export function summarizeChangelogRelease(version, changelogRoot) {
  const v = normalizeVersion(version);
  const seriesName = seriesFileNameForVersion(v);
  const seriesFile = path.join(changelogRoot, "series", seriesName);

  if (!fs.existsSync(seriesFile)) {
    throw new Error(
      `Series file not found: ${seriesFile}\nAppend detailed notes under ## ${v} (Unreleased) first.`,
    );
  }

  const markdown = fs.readFileSync(seriesFile, "utf8");
  const detailedBody = extractVersionSection(markdown, v);
  if (!detailedBody) {
    throw new Error(
      `No ## ${v} section in ${seriesFile}. Create it under (Unreleased) before summarizing.`,
    );
  }

  const releaseFile = path.join(changelogRoot, "releases", `${v}.md`);
  const releaseNotes = buildReleaseNotes(v, detailedBody);
  return { seriesFile, detailedBody, releaseFile, releaseNotes };
}

function main() {
  const args = process.argv.slice(2);
  const version = args.find((arg) => !arg.startsWith("-"));
  if (!version) {
    console.error(
      "Usage: summarize-changelog-release.mjs <version> [--write] [changelogDir]",
    );
    process.exit(2);
  }

  const write = args.includes("--write");
  const changelogArg = args.find(
    (arg) => !arg.startsWith("-") && arg !== version,
  );
  const here = path.dirname(fileURLToPath(import.meta.url));
  const changelogRoot =
    changelogArg || path.join(here, "..", "..", "changelog");

  const { releaseFile, releaseNotes } = summarizeChangelogRelease(
    version,
    changelogRoot,
  );

  if (write) {
    fs.mkdirSync(path.dirname(releaseFile), { recursive: true });
    fs.writeFileSync(releaseFile, releaseNotes, "utf8");
    console.error(`# wrote ${path.relative(process.cwd(), releaseFile)}`);
  } else {
    process.stdout.write(releaseNotes);
  }
}

const entry = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (entry.endsWith(`${path.sep}summarize-changelog-release.mjs`)) {
  try {
    main();
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
}
